// Files

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

pub fn layout_files() -> Vec<PathBuf> {
    layout_files::layout_paths(&root().join(layout_files::DIRECTORY))
}

pub fn read(path: &Path) -> LayoutFile {
    layout_files::read_file(path).unwrap_or_else(|error| panic!("{error}"))
}

// Generation

fn document(files: &[LayoutFile]) -> String {
    let mut text = format!(
        "# Keyboard layouts

[English](#english) · [Deutsch](#deutsch)

## English

FlexPad types text actions for the keyboard layout chosen in the profile. Each layout is a file in [`layouts`](layouts), which the firmware and the app compile in. The layouts follow the Windows and Linux layouts of the same name; macOS places some characters elsewhere.

All layout files were generated by Claude (AI). Files that a person has checked name the reviewer in the table and in the file itself. If a character is typed wrongly or a label is wrong, please open an [issue]({ISSUES}) or a pull request; reviewers are credited with their GitHub name if they agree.

### File format

A file `layouts/<code>.layout` is UTF-8 text with `key = value` lines; lines starting with `#` are comments. The code follows [BCP 47](https://www.rfc-editor.org/info/bcp47), the existing codes `us` and `de` stay as they are.

- `layout.name = German`: the English name. The app shows it unless its language file translates it as `layout.<code>`.
- `layout.fallback = de` (optional): labels and characters missing in the file are taken from this layout, unless their keys are already used.
- Labels, `KeyY = Z`: the label printed on a key position. Positions use the names of a US keyboard ([`KeyboardEvent.code`](https://developer.mozilla.org/en-US/docs/Web/API/UI_Events/Keyboard_event_code_values)).
- Characters, `ä = Quote`, `@ = AltGr+KeyQ`, `é = dead:Equal KeyE`: the keys that type a character. Modifiers are `Shift` and `AltGr`; `dead:` names a dead key followed by the key typed after it. Write `#` as `U+0023`; any character can be written as `U+` and its hexadecimal code.
- Uppercase letters are typed with Shift and need no line of their own, unless the Shift position already types something else. Space, Enter and Tab are built in.

Every character must map to a known key position, and no character and no key combination may be defined twice; otherwise the build fails. This list is generated from the files. After changing them, run `$env:{UPDATE_VARIABLE} = 1; cargo test layout_list` in `flexpad-desktop` to update it; the CI fails if it is out of date.

## Deutsch

FlexPad tippt Textaktionen für das im Profil gewählte Tastaturlayout. Jedes Layout ist eine Datei in [`layouts`](layouts), die Firmware und App beim Bauen einbinden. Die Layouts entsprechen den gleichnamigen Layouts unter Windows und Linux; macOS legt einige Zeichen auf andere Tasten.

Alle Layout-Dateien wurden von Claude (KI) erzeugt. Dateien, die eine Person geprüft hat, nennen die prüfende Person in der Tabelle und in der Datei selbst. Wenn ein Zeichen falsch getippt wird oder eine Beschriftung nicht stimmt, eröffne gern ein [Issue]({ISSUES}) oder einen Pull Request; mit Einverständnis wird die prüfende Person mit ihrem GitHub-Namen genannt.

### Dateiformat

Eine Datei `layouts/<code>.layout` ist UTF-8-Text mit Zeilen `Schlüssel = Wert`; Zeilen mit `#` am Anfang sind Kommentare. Der Code folgt [BCP 47](https://www.rfc-editor.org/info/bcp47), die bestehenden Codes `us` und `de` bleiben, wie sie sind.

- `layout.name = German`: der englische Name. Die App zeigt ihn an, sofern ihre Sprachdatei ihn nicht als `layout.<code>` übersetzt.
- `layout.fallback = de` (optional): Beschriftungen und Zeichen, die in der Datei fehlen, kommen aus diesem Layout, sofern ihre Tasten nicht schon belegt sind.
- Beschriftungen, `KeyY = Z`: die aufgedruckte Beschriftung einer Tastenposition. Positionen tragen die Namen einer US-Tastatur ([`KeyboardEvent.code`](https://developer.mozilla.org/en-US/docs/Web/API/UI_Events/Keyboard_event_code_values)).
- Zeichen, `ä = Quote`, `@ = AltGr+KeyQ`, `é = dead:Equal KeyE`: die Tasten, die ein Zeichen tippen. Umschalttasten sind `Shift` und `AltGr`; `dead:` nennt eine Tottaste und danach die Taste, die auf sie folgt. `#` wird als `U+0023` geschrieben; jedes Zeichen lässt sich als `U+` mit seinem hexadezimalen Code schreiben.
- Großbuchstaben werden mit Shift getippt und brauchen keine eigene Zeile, sofern die Shift-Belegung nicht schon ein anderes Zeichen tippt. Leerzeichen, Enter und Tab sind eingebaut.

Jedes Zeichen muss zu einer bekannten Tastenposition führen, und kein Zeichen und keine Tastenkombination darf doppelt vorkommen; sonst schlägt der Build fehl. Diese Liste wird aus den Dateien erzeugt. Nach Änderungen daran aktualisiert `$env:{UPDATE_VARIABLE} = 1; cargo test layout_list` in `flexpad-desktop` sie; die CI schlägt fehl, wenn sie veraltet ist.

## Layouts

| Code | Layout | Reviewed by |
|---|---|---|
"
    );
    for file in files {
        let reviewers = if file.reviewers.is_empty() {
            "–".to_owned()
        } else {
            file.reviewers
                .iter()
                .map(|name| format!("[@{name}](https://github.com/{name})"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(
            text,
            "| [`{code}`](layouts/{code}.layout) | {} | {reviewers} |",
            file.name,
            code = file.code
        );
    }
    text
}

// Tests

#[test]
fn layout_list_is_up_to_date() {
    let mut files: Vec<LayoutFile> = layout_files().iter().map(|path| read(path)).collect();
    files.sort_by(|left, right| left.code.cmp(&right.code));
    for file in &files {
        assert_eq!(
            file.title.as_deref(),
            Some(format!("{} ({})", file.name, file.code).as_str()),
            "{}: the title must be the English name followed by the code",
            file.code
        );
    }
    let expected = document(&files);
    let path = root().join(DOCUMENT);
    if env::var_os(UPDATE_VARIABLE).is_some() {
        fs::write(&path, &expected).unwrap();
    }
    let actual = fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        actual == expected,
        "LAYOUTS.md is out of date, run `$env:{UPDATE_VARIABLE} = 1; cargo test layout_list`"
    );
}

#[test]
fn every_file_is_compiled_in() {
    let files = layout_files();
    assert_eq!(files.len(), KeyboardLayout::ALL.len());
    let layouts = resolve(&files.iter().map(|path| read(path)).collect::<Vec<_>>()).unwrap();
    for layout in layouts {
        let compiled = KeyboardLayout::from_name(&layout.code).unwrap();
        assert_eq!(compiled.code(), layout.code);
        assert_eq!(
            compiled.characters().count(),
            layout.characters.len(),
            "{}",
            layout.code
        );
        for (character, strokes) in &layout.characters {
            let typed = crate::keys::firmware_keystrokes(compiled, *character).unwrap();
            assert_eq!(
                (
                    typed.dead_key.map(|key| (key.modifiers, key.usage)),
                    typed.key.modifiers,
                    typed.key.usage
                ),
                (
                    strokes.dead_key.map(|key| (key.modifiers, key.usage)),
                    strokes.key.modifiers,
                    strokes.key.usage
                ),
                "{} {character:?}",
                layout.code
            );
        }
    }
}

// Format

const HEADER: &str = "# FlexPad keyboard layout: Test (xx)\nlayout.name = Test\n";

fn strokes(content: &str, character: char) -> Option<Keystrokes> {
    let file = parse("us", &format!("{HEADER}{content}")).unwrap();
    resolve(&[file]).unwrap()[0]
        .characters
        .get(&character)
        .copied()
}

fn single(modifiers: u8, usage: u8) -> Keystrokes {
    Keystrokes {
        dead_key: None,
        key: Stroke { modifiers, usage },
    }
}

#[test]
fn parses_characters_labels_and_settings() {
    let file = parse(
        "de",
        &format!("{HEADER}# Reviewed by: @someone, @other\nKeyY = Z\nä = Quote\n@ = AltGr+KeyQ\nU+0023 = IntlHash\n= = Shift+Digit0\né = dead:Equal KeyE\n"),
    )
    .unwrap();
    assert_eq!(file.name, "Test");
    assert_eq!(file.title.as_deref(), Some("Test (xx)"));
    assert_eq!(file.reviewers, ["someone", "other"]);
    assert_eq!(file.labels["KeyY"], "Z");
    assert_eq!(file.characters[&'ä'], single(0, 0x34));
    assert_eq!(file.characters[&'@'], single(0x40, 0x14));
    assert_eq!(file.characters[&'#'], single(0, 0x32));
    assert_eq!(file.characters[&'='], single(0x02, 0x27));
    assert_eq!(
        file.characters[&'é'],
        Keystrokes {
            dead_key: Some(Stroke {
                modifiers: 0,
                usage: 0x2E
            }),
            key: Stroke {
                modifiers: 0,
                usage: 0x08
            },
        }
    );
}

#[test]
fn derives_uppercase_letters_and_whitespace() {
    assert_eq!(strokes("ä = Quote\n", 'Ä'), Some(single(0x02, 0x34)));
    assert_eq!(strokes("ä = Quote\n% = Shift+Quote\n", 'Ä'), None);
    assert_eq!(strokes("µ = AltGr+KeyM\n", 'Μ'), None);
    assert_eq!(strokes("ß = Minus\n", 'ẞ'), None);
    assert_eq!(
        strokes("é = dead:Equal KeyE\n", 'É'),
        Some(Keystrokes {
            dead_key: Some(Stroke {
                modifiers: 0,
                usage: 0x2E
            }),
            key: Stroke {
                modifiers: 0x02,
                usage: 0x08
            },
        })
    );
    assert_eq!(strokes("", ' '), Some(single(0, 0x2C)));
    assert_eq!(strokes("", '\n'), Some(single(0, 0x28)));
}

#[test]
fn falls_back_to_another_layout() {
    let base = parse(
        "us",
        &format!("{HEADER}Minus = -\nSlash = /\n- = Minus\n/ = Slash\n? = Shift+Slash\n"),
    )
    .unwrap();
    let child = parse(
        "de",
        &format!("{HEADER}layout.fallback = us\nMinus = ß\nß = Minus\n_ = Shift+Slash\n"),
    )
    .unwrap();
    let layouts = resolve(&[base, child]).unwrap();
    let german = layouts.iter().find(|layout| layout.code == "de").unwrap();
    assert_eq!(german.labels["Minus"], "ß");
    assert_eq!(german.labels["Slash"], "/");
    assert_eq!(german.characters.get(&'/'), Some(&single(0, 0x38)));
    assert_eq!(german.characters.get(&'-'), None);
    assert_eq!(german.characters.get(&'?'), None);
}

#[test]
fn rejects_invalid_files() {
    let error = |content: &str| parse("xx", &format!("{HEADER}{content}")).unwrap_err();
    assert!(error("a = KeyA\na = KeyB\n").contains("twice"));
    assert!(error("a = KeyA\nb = KeyA\n").contains("same keys"));
    assert!(error("a = Hyper\n").contains("unknown key"));
    assert!(error("a = Ctrl+KeyA\n").contains("unknown modifier"));
    assert!(error("a = ShiftLeft\n").contains("modifier"));
    assert!(error("a = dead:Equal\n").contains("dead key"));
    assert!(error("Hyper = H\n").contains("unknown key"));
    assert!(error("layout.colour = red\n").contains("unknown setting"));
    assert!(error("KeyA\n").contains("="));
    assert!(error("U+D800 = KeyA\n").contains("valid character"));
    assert!(
        parse("xx", "a = KeyA\n")
            .unwrap_err()
            .contains("layout.name")
    );
    assert!(parse("bad code", HEADER).is_err());

    let file = |code: &str, extra: &str| parse(code, &format!("{HEADER}{extra}")).unwrap();
    assert!(
        resolve(&[file("de", "")])
            .unwrap_err()
            .contains("default layout")
    );
    assert!(
        resolve(&[
            file("us", "layout.fallback = de\n"),
            file("de", "layout.fallback = us\n")
        ])
        .unwrap_err()
        .contains("leads back")
    );
    assert!(
        resolve(&[file("us", "layout.fallback = xx\n")])
            .unwrap_err()
            .contains("unknown layout")
    );
    assert!(
        resolve(&[file("us", ""), file("US", "")])
            .unwrap_err()
            .contains("twice")
    );
}
